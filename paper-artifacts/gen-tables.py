    p = SCRIPT_DIR.parent / "pop-pay-npm"
    if (p / "tests" / "redteam" / "runs" / "adaptive").exists():
        return p
    # Final fallback (let downstream FATAL message report the missing path)
    return SCRIPT_DIR.parent / "pop-pay-npm"


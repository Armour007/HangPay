#!/usr/bin/env python3
"""
gen-tables.py — Reproducibility bridge: pop-pay-npm JSONL run files -> LaTeX
table source for the paper's headline tables.

Closes the R18 Round-3 reviewer critique that "no published paper/gen-tables.py
script ties JSONL -> published Tables 4/6/etc." Reproducers can now regenerate
the published LaTeX tables from the released JSONL run files without
reverse-engineering the harness source.

WHAT THIS EMITS
---------------
* tab:bypassk        — Per-model cumulative Bypass@K under the PRIMARY
                       (whitebox-no-feedback) threat model, K=1..5,10,20, with
                       95% bootstrap CIs (1000 payload-level resamples,
                       seed=42) on the headline K=5 / K=20 / Never columns.
                       Mirrors the K=20 "merged-cumulative" entries for the
                       four models with cross-attacker K=20 cumulative jsons
                       (Pro x GPT, Pro x Opus, Sonnet x GPT, Flash x GPT,
                       Nano x Opus) only when --use-cumulative is passed; by
                       default it emits the same-family Pro-attacker numbers
                       that populate Tab.~ref{tab:bypassk}.
* tab:bypassk_cat    — Per-model per-category Bypass@5 under PRIMARY (11
                       categories x 9 models). Bolded winners are the lowest
                       (most resilient) per row; this matches the visual
                       presentation of Tab.~ref{tab:bypassk_cat} in the paper
                       (which is currently rendered from legacy informed-mode
                       data; the PRIMARY-mode version emitted here is the
                       supplementary table referenced in the paper caption).

INPUT FILES (PRIMARY whitebox-no-feedback, 9 models)
----------------------------------------------------
The 2026-04-28T19-50-* family of JSONL files in
  pop-pay-npm/tests/redteam/runs/adaptive/
The exact filenames are pinned in the PRIMARY_FILES map below; identical to
the mapping in pop-pay-npm/tests/redteam/scripts/compute-ci.py.

SHA-PINNING
-----------
SHA-256 hashes for the cross-attacker K=20 cumulative JSONL inputs
(F5-Pro K=5 snapshot, F5-Pro-K20 fresh-subset, F5-FlashGPT K=5 snapshot,
F5-FlashGPT-K20Tail final, F5-Nano-Opus 418-row partial, F5-Nano-Opus-Tail
51-row recovery, plus the corpus and L2 prompt template) are pinned in
pop-pay-npm/tests/redteam/scripts/verify-paper-numbers.sh; that script is
the canonical integrity gate. The PRIMARY 9-model JSONL files do not yet
have SHA pins in verify-paper-numbers.sh; reproducers should re-shasum
their on-disk copies and confirm against the MANIFEST.sha256 generated by
tests/redteam/scripts/generate-manifest.py.

METHODOLOGY
-----------
* Bypass@K per payload: 1 if (bypass_at_k != null AND bypass_at_k <= K),
  else 0. Identical to the harness definition (Section 4.1 of the paper).
* Bootstrap CI: payload-level resampling, 1000 resamples, percentile
  method (2.5/97.5), seed=42. Matches compute-ci.py.
* Per-category Bypass@5: same indicator, partitioned by row['category'];
  bolded winner per row = argmin point estimate.

USAGE
-----
    python3 paper/gen-tables.py --table bypassk
    python3 paper/gen-tables.py --table percategory
    python3 paper/gen-tables.py --table all --output stdout
    python3 paper/gen-tables.py --table all --output paper/auto-tables.tex

The default --output is stdout. When --output is a file path, the script
writes a single .tex fragment with both tables separated by clear
section comments.

REPRODUCIBILITY STATEMENT
-------------------------
This script is intentionally stdlib-only (no numpy/scipy) so a reproducer
can run it with a stock python3 install. Bootstrap RNG is python.random
seeded at 42; identical seeds yield identical CIs across runs.

If the script's output diverges from the published table by more than
+/- 0.1pp on a point estimate or +/- 0.5pp on a CI bound, that is a
reproducibility regression and should be reported as a paper issue.
"""

